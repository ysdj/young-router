import { build } from "esbuild";
import { readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "packages/shared/src/ui/code-editor/CodeEditorWeb.ts");
const temporaryBundle = resolve(root, "packages/shared/src/ui/code-editor/.CodeEditorWeb.bundle.js");
const output = resolve(root, "packages/shared/src/ui/code-editor/CodeEditorWebBundle.ts");

await build({
  bundle: true,
  entryPoints: [source],
  format: "iife",
  legalComments: "none",
  minify: true,
  outfile: temporaryBundle,
  platform: "browser",
  target: ["es2020"],
});

const bundle = await readFile(temporaryBundle, "utf8");
const contents = [
  "// Generated by scripts/build-code-editor.mjs. Do not edit directly.",
  `export const CODE_EDITOR_WEB_BUNDLE = ${JSON.stringify(bundle)};`,
  "",
].join("\n");
// Write only when the bundle actually changed.  This file is a source input to
// the type check and to Metro's transform graph, so republishing identical
// bytes still bumps its mtime and makes downstream caches treat an unchanged
// editor as a change on every build.
let existing = null;
try {
  existing = await readFile(output, "utf8");
} catch {
  existing = null;
}
if (existing !== contents) {
  await writeFile(output, contents);
}
await rm(temporaryBundle, { force: true });
