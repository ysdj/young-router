import { build } from "esbuild";
import { readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "packages/shared/src/ui/code-editor/CodeEditorWeb.ts");
const temporaryBundle = resolve(root, "packages/shared/src/ui/code-editor/.CodeEditorWeb.bundle.js");
const output = resolve(root, "packages/shared/src/ui/code-editor/CodeEditorWebBundle.ts");

await build({
  bundle: true,
  entryPoints: [source],
  format: "iife",
  legalComments: "none",
  minify: true,
  outfile: temporaryBundle,
  platform: "browser",
  target: ["es2020"],
});

const bundle = await readFile(temporaryBundle, "utf8");
await writeFile(
  output,
  [
    "// Generated by scripts/build-code-editor.mjs. Do not edit directly.",
    `export const CODE_EDITOR_WEB_BUNDLE = ${JSON.stringify(bundle)};`,
    "",
  ].join("\n"),
);
await rm(temporaryBundle, { force: true });
